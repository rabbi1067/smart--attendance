'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'..','frontend');
const html=fs.readFileSync(path.join(root,'admin.html'),'utf8');
const js=fs.readFileSync(path.join(root,'admin.js'),'utf8');
const publicHtml=fs.readFileSync(path.join(root,'index.html'),'utf8');
const ids=source=>new Set([...source.matchAll(/\bid=["']([^"']+)["']/g)].map(m=>m[1]));
const domRefs=source=>new Set([...source.matchAll(/\$\(["']([\w-]+)["']\)/g)].map(m=>m[1]));
const adminIds=ids(html),publicIds=ids(publicHtml);
for(const ref of domRefs(js))assert.ok(adminIds.has(ref),`Admin JavaScript references missing DOM element: ${ref}`);
for(const ref of domRefs(publicHtml))assert.ok(publicIds.has(ref),`Public JavaScript references missing DOM element: ${ref}`);
assert.equal(adminIds.size,[...html.matchAll(/\bid=["']([^"']+)["']/g)].length,'Duplicate admin DOM ids');
assert.equal(publicIds.size,[...publicHtml.matchAll(/\bid=["']([^"']+)["']/g)].length,'Duplicate public DOM ids');
new vm.Script(js,{filename:'admin.js'});
for(const script of publicHtml.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi))new vm.Script(script[1],{filename:'index-inline.js'});
assert.match(js,/function todayDhakaISO\(/);
assert.match(js,/recordId:currentDelete\.recordId/);
assert.doesNotMatch(js,/rowIndex:currentDelete\.rowIndex/);
assert.match(js,/closeEditor\(\);await loadSheets\(\)/);
assert.match(js,/await loadSheets\(\);notice\('✓ Record deleted/);
assert.match(js,/header\.toLowerCase\(\)==='date'\)\{input\.type='date'/);
assert.doesNotMatch(publicHtml,/emailjs\.send\(/i,'Browser should not send student confirmation messages directly');
console.log(`Frontend contract tests passed: Admin ${adminIds.size} IDs, public ${publicIds.size} IDs, syntax, date/editor/refresh/email guards.`);
